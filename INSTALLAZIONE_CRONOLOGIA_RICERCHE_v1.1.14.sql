CREATE TABLE IF NOT EXISTS public.cronologia_ricerche (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE DEFAULT auth.uid(),
  operatore TEXT NOT NULL,
  termine TEXT NOT NULL CHECK (length(btrim(termine)) BETWEEN 1 AND 200),
  provenienza TEXT NOT NULL DEFAULT 'scrivania',
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS cronologia_ricerche_data_idx
  ON public.cronologia_ricerche (created_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS cronologia_ricerche_user_data_idx
  ON public.cronologia_ricerche (user_id, created_at DESC);
ALTER TABLE public.cronologia_ricerche ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.cronologia_ricerche FROM anon;
GRANT SELECT, INSERT ON public.cronologia_ricerche TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.cronologia_ricerche_id_seq TO authenticated;

-- L'operatore può registrare solo le proprie ricerche.
DROP POLICY IF EXISTS cronologia_insert_propria ON public.cronologia_ricerche;
CREATE POLICY cronologia_insert_propria ON public.cronologia_ricerche
  FOR INSERT TO authenticated WITH CHECK (user_id = auth.uid());

-- L'operatore legge le proprie ricerche. Per l'admin, il ruolo dev'essere
-- attribuito da Supabase Auth app_metadata (NON da user_metadata modificabili).
-- Per attivare la vista generale, app_metadata deve contenere {"role":"admin"}.
DROP POLICY IF EXISTS cronologia_select_autorizzata ON public.cronologia_ricerche;
CREATE POLICY cronologia_select_autorizzata ON public.cronologia_ricerche
  FOR SELECT TO authenticated USING (
    user_id = auth.uid()
    OR coalesce(auth.jwt() -> 'app_metadata' ->> 'role', '') = 'admin'
  );
